const gkey = (w) => w.toLowerCase().replace(/ё/g, 'е');
const GLOSS = {};
(function buildGloss() {
  GLOSS_TEXT.split('\n').forEach((l) => {
    const p = l.split('|');
    if (p.length >= 3) GLOSS[gkey(p[0].trim())] = [p[1].trim(), p.slice(2).join('|').trim()];
  });
  // single words from the study decks fill the rest
  [DECKS, DECKS_MID, DECKS_PRO, DECKS_FAMILY].forEach((decks) => {
    Object.values(decks).forEach((list) => list.forEach(([ru, tr, en]) => {
      const w = ru.replace(/[…?!]/g, '').trim();
      if (w && !/\s/.test(w) && !GLOSS[gkey(w)]) GLOSS[gkey(w)] = [tr, en];
    }));
  });
})();

const WORD_RE = /[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*/g;
// Splits a Russian line into its words, each with how it sounds and what it means.
function lineWords(ru) {
  return (ru.match(WORD_RE) || []).map((w) => {
    const g = GLOSS[gkey(w)];
    return { w, tr: g ? g[0] : '', en: g ? g[1] : '' };
  });
}
